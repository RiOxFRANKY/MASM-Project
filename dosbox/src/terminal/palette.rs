const COLORS: [(u8, u8, u8); 16] = [
    (0x00, 0x00, 0x00),
    (0x00, 0x00, 0xAA),
    (0x00, 0xAA, 0x00),
    (0x00, 0xAA, 0xAA),
    (0xAA, 0x00, 0x00),
    (0xAA, 0x00, 0xAA),
    (0xAA, 0x55, 0x00),
    (0xAA, 0xAA, 0xAA),
    (0x55, 0x55, 0x55),
    (0x55, 0x55, 0xFF),
    (0x55, 0xFF, 0x55),
    (0x55, 0xFF, 0xFF),
    (0xFF, 0x55, 0x55),
    (0xFF, 0x55, 0xFF),
    (0xFF, 0xFF, 0x55),
    (0xFF, 0xFF, 0xFF),
];

pub fn colors(attribute: u8, blink: bool) -> ((u8, u8, u8), (u8, u8, u8)) {
    let background_mask = if blink { 0x07 } else { 0x0F };
    (COLORS[(attribute & 0x0F) as usize], COLORS[((attribute >> 4) & background_mask) as usize])
}

pub fn escape_for(attribute: u8, blink: bool) -> String {
    let ((fr, fg, fb), (br, bg, bb)) = colors(attribute, blink);
    format!("\x1b[38;2;{fr};{fg};{fb};48;2;{br};{bg};{bb}m")
}
