pub fn to_unicode(byte: u8) -> char {
    match byte {
        0x00..=0x1F => LOW[byte as usize],
        0x7F => '⌂',
        0x80..=0xFF => HIGH[(byte - 0x80) as usize],
        _ => byte as char,
    }
}

pub fn from_unicode(character: char) -> u8 {
    if (character as u32) < 0x80 {
        return character as u8;
    }
    HIGH.iter()
        .position(|candidate| *candidate == character)
        .map(|position| position as u8 + 0x80)
        .unwrap_or(b'?')
}
